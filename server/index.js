/**
 * Главный файл сервера ScreenCode
 *
 * Точка входа Node.js-приложения. Выполняет:
 * - Загрузку переменных окружения из .env
 * - Подключение к MongoDB Atlas
 * - Настройку middleware (CORS, JSON parser)
 * - Регистрацию маршрутов API
 * - Запуск HTTP-сервера
 *
 * Архитектура:
 * - Express.js как HTTP-фреймворк
 * - MongoDB Atlas как облачная база данных
 * - Все бизнес-логика вынесена в отдельные модули routes/
 * - Middleware авторизации применяется точечно в маршрутах
 *
 * Переменные окружения (.env):
 * - PORT: порт сервера (по умолчанию 3001)
 * - MONGO_URI: строка подключения к MongoDB Atlas
 * - JWT_SECRET: секретный ключ для подписи JWT-токенов
 * - RESEND_API_KEY: ключ API сервиса Resend (для отправки писем)
 * - FRONTEND_URL: URL фронтенда для формирования ссылок в письмах
 *
 * @module server/index
 */

// ═══════════════════════════════════════════════════════════════
// ИМПОРТЫ
// ═══════════════════════════════════════════════════════════════

const express = require('express')
const cors = require('cors')
require('dotenv').config()
const connectDB = require('./db/connect')

// Хранилище данных последней генерации (в памяти)
// Используется отладочным эндпоинтом /api/last-debug
const lastGenerationDebug = require('./debugStore')

// ═══════════════════════════════════════════════════════════════
// ИНИЦИАЛИЗАЦИЯ EXPRESS
// ═══════════════════════════════════════════════════════════════

const app = express()

// ═══════════════════════════════════════════════════════════════
// ПОДКЛЮЧЕНИЕ К БАЗЕ ДАННЫХ
// ═══════════════════════════════════════════════════════════════

// Подключаемся к MongoDB асинхронно, не блокируя запуск сервера.
// Если подключение упадёт — connectDB сам вызовет process.exit(1).
connectDB()

// ═══════════════════════════════════════════════════════════════
// MIDDLEWARE
// ═══════════════════════════════════════════════════════════════

/**
 * CORS (Cross-Origin Resource Sharing)
 *
 * Разрешает запросы с фронтенда (localhost:5173 в dev, Vercel в prod).
 * В текущей конфигурации разрешает все источники — для open-source проекта
 * это приемлемо, так как авторизация идёт через JWT.
 *
 * Для продакшена рекомендуется ограничить origins:
 * cors({ origin: process.env.FRONTEND_URL })
 */
app.use(cors())

/**
 * Парсер JSON-тела запросов
 *
 * Лимит 50mb необходим для обработки больших base64-изображений,
 * которые могут приходить в JSON-запросах (например, при восстановлении
 * генерации с большими файлами). Стандартный лимит Express — 100kb.
 */
app.use(express.json({ limit: '50mb' }))

// ═══════════════════════════════════════════════════════════════
// СЛУЖЕБНЫЕ МАРШРУТЫ (Health Check, Models)
// ═══════════════════════════════════════════════════════════════

/**
 * GET /api/health — Health Check
 *
 * Используется для мониторинга доступности сервера:
 * - Load balancer'ами (Vercel, Render)
 * - Системами мониторинга (UptimeRobot, Pingdom)
 * - Docker healthcheck
 */
app.get('/api/health', (req, res) => {
    res.json({ status: 'ok', message: 'Сервер работает' })
})

/**
 * GET /api/models — Список доступных моделей
 *
 * Возвращает модели, которые можно использовать для генерации.
 * В текущей версии (BYOK) пользователь вводит свою модель,
 * но этот эндпоинт может использоваться для UI-подсказок.
 *
 */
app.get('/api/models', (req, res) => {
    res.json({
        models: [
            { id: process.env.AI_MODEL || 'qwen/qwen3.6-plus', name: 'Qwen 3.6' },
        ]
    })
})

// ═══════════════════════════════════════════════════════════════
// ОСНОВНЫЕ МАРШРУТЫ API
// ═══════════════════════════════════════════════════════════════

/**
 * Порядок регистрации маршрутов важен:
 * Express обрабатывает их сверху вниз, поэтому более специфичные
 * маршруты должны идти раньше общих.
 */

// Отладочные маршруты (для разработчиков, без авторизации)
app.use('/api/debug', require('./routes/debug'))

// Маршруты аутентификации (регистрация, вход, сброс пароля)
app.use('/api/auth', require('./routes/auth'))

// Маршруты истории генераций (CRUD, требует авторизации)
app.use('/api/history', require('./routes/history'))

// Главный маршрут генерации кода (требует авторизации + API-ключ)
app.use('/api/generate', require('./routes/generate'))

/**
 * GET /api/last-debug — Получение данных последней генерации
 *
 * Возвращает промпты, изображения и результаты анализа последней
 * генерации для отладки через DebugPage. Данные хранятся в памяти
 * сервера (lastGenerationDebug) и перезаписываются при каждой генерации.
 *
 * ⚠️ Ограничения:
 * - Данные теряются при перезапуске сервера
 * - При масштабировании на несколько инстансов каждый хранит свои данные
 * - Для продакшена заменить на Redis или MongoDB
 */
app.get('/api/last-debug', (req, res) => {
    res.json(lastGenerationDebug)
})

// Маршрут точечного редактирования кода (требует API-ключ)
app.use('/api/edit', require('./routes/edit'))

// ═══════════════════════════════════════════════════════════════
// ОБРАБОТЧИК ОШИБОК (должен быть после всех маршрутов)
// ═══════════════════════════════════════════════════════════════

/**
 * Глобальный обработчик ошибок Express
 *
 * Ловит все необработанные ошибки из маршрутов и возвращает
 * единообразный JSON-ответ. Важно: функция должна иметь 4 параметра
 * (err, req, res, next), иначе Express не распознает её как error handler.
 */
app.use((err, req, res, next) => {
    console.error('Необработанная ошибка:', err.message)
    res.status(err.status || 500).json({
        error: err.message || 'Внутренняя ошибка сервера'
    })
})

// ═══════════════════════════════════════════════════════════════
// ЗАПУСК СЕРВЕРА
// ═══════════════════════════════════════════════════════════════

const PORT = process.env.PORT || 3001

app.listen(PORT, () => {
    console.log(`\n🚀 Сервер ScreenCode запущен`)
    console.log(`   URL: http://localhost:${PORT}`)
    console.log(`   Health: http://localhost:${PORT}/api/health`)
    console.log(`   Debug: http://localhost:${PORT}/api/last-debug\n`)
})