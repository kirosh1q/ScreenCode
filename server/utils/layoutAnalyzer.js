/**
 * Модуль программного анализа макета интерфейса (без AI)
 *
 * Выполняет низкоуровневый анализ пиксельных данных изображения для выявления
 * структурных особенностей, которые сложно или дорого определять через AI:
 * - Поиск горизонтальных секций по перепадам яркости
 * - Обнаружение повторяющихся паттернов (карточки, списки, таблицы)
 *
 * Архитектурная роль:
 * Результаты анализа используются в промптах Pass 1 и Pass 2 для повышения
 * точности генерации. Например, информация о повторяющихся блоках помогает
 * модели понять, что нужно создать компонент-список, а не копировать код.
 *
 * Входные данные:
 * Все функции принимают сырой буфер пикселей из processImageForAnalysis()
 * (формат RGB, 3 байта на пиксель, без альфа-канала).
 *
 * @module utils/layoutAnalyzer
 */

