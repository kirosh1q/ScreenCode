/**
 * Определяет наличие повторяющихся блоков в интерфейсе
 *
 * Алгоритм:
 * 1. Скользит по изображению горизонтальной полосой высотой 40px
 * 2. Для каждой позиции формирует "сигнатуру" — 20 квантованных значений яркости
 * 3. Сравнивает все пары сигнатур между собой
 * 4. Если相似度 > 0.8 — считает полосы похожими
 * 5. Если найдено > 5 похожих пар — интерфейс содержит повторяющиеся элементы
 *
 * Зачем это нужно:
 * Позволяет определить, есть ли в интерфейсе списки, карточки, таблицы
 * или другие повторяющиеся паттерны. Эта информация передаётся в промпт
 * Pass 1, чтобы модель создала компонент-список вместо копирования кода.
 *
 * Примеры обнаружения:
 * - Список товаров (одинаковые карточки друг под другом)
 * - Таблица с данными (повторяющиеся строки)
 * - Галерея изображений (одинаковые превью)
 *
 * @param {Buffer} buffer - Сырой RGB-буфер пикселей (из processImageForAnalysis)
 * @param {number} width - Ширина изображения в пикселях
 * @param {number} height - Высота изображения в пикселях
 * @returns {boolean} true, если обнаружены повторяющиеся блоки
 *
 * @example
 * const { rawPixels, info } = await processImageForAnalysis(buffer)
 * const hasRepeating = detectRepeatingBlocks(rawPixels, info.width, info.height)
 * if (hasRepeating) {
 *     // В промпте указываем: "interface contains repeating card components"
 * }
 */
function detectRepeatingBlocks(buffer, width, height) {
    // Высота скользящего окна — 40px. Этого достаточно, чтобы захватить
    // типичную высоту карточки или строки таблицы, но не слишком много,
    // чтобы не смазывать детали.
    const sliceH = 40
    const signatures = []

    // Формируем сигнатуры для каждой горизонтальной полосы
    for (let y = 0; y < height - sliceH; y += sliceH) {
        const sig = []

        // Берём 20 точек по горизонтали — этого достаточно для описания
        // структуры полосы (светлые/тёмные зоны).
        // Квантуем яркость делением на 30 — это снижает чувствительность
        // к шуму и небольшим различиям в освещении.
        for (let x = 0; x < width; x += Math.floor(width / 20)) {
            const idx = (y * width + x) * 3
            if (idx + 2 < buffer.length) {
                // Квантование: яркость 0-255 → 0-8 (8 уровней)
                sig.push(Math.floor((buffer[idx] + buffer[idx + 1] + buffer[idx + 2]) / 3 / 30))
            }
        }
        signatures.push({ y, sig })
    }

    // Сравниваем все пары сигнатур между собой
    let repeatCount = 0
    for (let i = 0; i < signatures.length; i++) {
        // Начинаем с i+2, чтобы сравнивать только неподряд идущие полосы
        // (соседние полосы часто похожи из-за плавных переходов)
        for (let j = i + 2; j < signatures.length; j++) {
            const similarity = calcSimilarity(signatures[i].sig, signatures[j].sig)
            // Порог 0.8 — высокая схожесть, но не идентичность
            // (идентичных полос в реальном UI почти не бывает из-за данных)
            if (similarity > 0.8) repeatCount++
        }
    }

    // Если найдено > 5 похожих пар — интерфейс содержит повторяющиеся элементы.
    // Порог 5 — эмпирический: меньше даёт ложные срабатывания на простых UI,
    // больше — пропускает списки из 2-3 элементов.
    return repeatCount > 5
}

// ═══════════════════════════════════════════════════════════════
// ФУНКЦИЯ: calcSimilarity — Вычисление схожести сигнатур
// ═══════════════════════════════════════════════════════════════

/**
 * Вычисляет степень схожести двух сигнатур яркости
 *
 * Метод: нормализованное расстояние Манхэттена
 * - Суммирует абсолютные разности между соответствующими значениями
 * - Нормализует на длину сигнатуры и максимальную разницу (8 уровней квантования)
 * - Возвращает значение от 0 (полностью разные) до 1 (идентичные)
 *
 * @param {Array<number>} a - Первая сигнатура (массив квантованных значений яркости)
 * @param {Array<number>} b - Вторая сигнатура
 * @returns {number} Коэффициент схожести (0.0 - 1.0)
 *
 * @example
 * calcSimilarity([1, 2, 3, 4], [1, 2, 3, 4])  // 1.0 (идентичные)
 * calcSimilarity([1, 2, 3, 4], [5, 6, 7, 8])  // 0.5 (разные)
 * calcSimilarity([], [])                       // 0 (пустые — защита от деления на 0)
 */
function calcSimilarity(a, b) {
    // Защита от невалидных входных данных
    if (a.length !== b.length || a.length === 0) return 0

    let diff = 0
    for (let i = 0; i < a.length; i++) {
        diff += Math.abs(a[i] - b[i])
    }

    // Нормализация: делим на (длина * максимальная_разница)
    // Максимальная разница = 8, так как квантование даёт значения 0-8
    return 1 - diff / (a.length * 8)
}

