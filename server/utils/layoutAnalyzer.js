// ФУНКЦИЯ: findHorizontalSections — Поиск секций по яркости
// ═══════════════════════════════════════════════════════════════

/**
 * Находит горизонтальные секции интерфейса по перепадам яркости
 *
 * Алгоритм:
 * 1. Делит изображение на 10 горизонтальных полос равной высоты
 * 2. Для каждой полосы вычисляет среднюю яркость (сэмплируя каждый 4-й пиксель)
 * 3. Если разница яркости между соседними полосами > 30 — это граница секции
 * 4. Группирует полосы в секции с классификацией по типу (dark/light/medium)
 *
 * Зачем это нужно:
 * Позволяет определить вертикальную структуру страницы (хедер/контент/футер)
 * без AI. Используется для валидации результатов Pass 1 или как fallback.
 *
 * ⚠️ В текущей версии не используется напрямую в generate.js.
 * Сохранена для возможного использования в будущих версиях и для отладки.
 *
 * @param {Buffer} buffer - Сырой RGB-буфер пикселей (из processImageForAnalysis)
 * @param {number} width - Ширина изображения в пикселях
 * @param {number} height - Высота изображения в пикселях
 * @returns {Array<Object>} Массив найденных секций
 *   - topPercent: number — верхняя граница (% от высоты)
 *   - heightPercent: number — высота секции (% от высоты)
 *   - avgBrightness: number — средняя яркость (0-255)
 *   - type: 'dark' | 'light' | 'medium' — тип секции по яркости
 *
 * @example
 * const { rawPixels, info } = await processImageForAnalysis(buffer)
 * const sections = findHorizontalSections(rawPixels, info.width, info.height)
 * // [
 * //   { topPercent: 0, heightPercent: 15, avgBrightness: 45, type: 'dark' },
 * //   { topPercent: 15, heightPercent: 70, avgBrightness: 220, type: 'light' },
 * //   { topPercent: 85, heightPercent: 15, avgBrightness: 30, type: 'dark' }
 * // ]
 */
function findHorizontalSections(buffer, width, height) {
    const sections = []

    // Делим изображение на 10 горизонтальных полос равной высоты.
    // 10 полос — баланс между детализацией и производительностью:
    // меньше полос — пропустим тонкие секции, больше — шум и ложные срабатывания.
    const sliceH = Math.floor(height / 10)

    let prevAvg = -1
    let sectionStart = 0

    for (let row = 0; row < 10; row++) {
        const y = row * sliceH
        let brightnessSum = 0
        let pixelCount = 0

        // Сэмплируем каждый 4-й пиксель по горизонтали для производительности.
        // Полный проход по всем пикселям дал бы почти тот же результат,
        // но в 4 раза медленнее.
        for (let x = 0; x < width; x += 4) {
            const idx = (y * width + x) * 3  // *3 — RGB (3 байта на пиксель)
            if (idx + 2 < buffer.length) {
                // Средняя яркость = (R + G + B) / 3
                brightnessSum += (buffer[idx] + buffer[idx + 1] + buffer[idx + 2]) / 3
                pixelCount++
            }
        }

        const avg = pixelCount > 0 ? Math.round(brightnessSum / pixelCount) : 0

        // Резкий перепад яркости (> 30 единиц) = граница между секциями.
        // Порог 30 — эмпирически подобран: меньше даёт ложные срабатывания
        // на градиентах, больше — пропускает реальные границы.
        if (prevAvg >= 0 && Math.abs(avg - prevAvg) > 30) {
            sections.push({
                topPercent: Math.round((sectionStart / height) * 100),
                heightPercent: Math.round(((y - sectionStart) / height) * 100),
                avgBrightness: prevAvg,
                type: prevAvg < 80 ? 'dark' : prevAvg > 180 ? 'light' : 'medium'
            })
            sectionStart = y
        }

        prevAvg = avg
    }

    // Добавляем последнюю секцию (от последней границы до низа изображения)
    sections.push({
        topPercent: Math.round((sectionStart / height) * 100),
        heightPercent: Math.round(((height - sectionStart) / height) * 100),
        avgBrightness: prevAvg,
        type: prevAvg < 80 ? 'dark' : prevAvg > 180 ? 'light' : 'medium'
    })

    return sections
}

